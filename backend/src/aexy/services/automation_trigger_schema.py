def trigger_fields_for(
    module: str, trigger_type: str | None
) -> tuple[tuple[str, str, str, str], ...]:
    """The fields a given module/trigger pair actually delivers.

    Empty when the pair is unknown — an honest empty list beats inventing paths
    that fail at run time. The picker still accepts a custom
    ``{{trigger.<key>}}`` for anyone working from a payload we have not mapped.
    """
    if module == "crm":
        return _CRM_TRIGGER_FIELDS.get(trigger_type or "", ())
    return _MODULE_TRIGGER_FIELDS.get(module, {}).get(trigger_type or "", ())
