"""What each automation trigger puts in `trigger_data`, for the field picker.

The builder may only offer a variable that resolves at execution time. An
unknown path is not cosmetic: the canvas/Temporal executor fails the step with
"Dynamic value '{{...}}' is missing", and the inline executor renders the
literal braces into the email or webhook body.

So none of this is hand-authored from the trigger names. Every key below was
read off the service that dispatches that event — CRMEventService, the CRM
schedule runner, and the ~80 dispatch_automation_event call sites across
ticket_service, hiring, campaign_service, uptime_service, the sprint services,
form_submission_handler, booking, tracking_events and compliance_service.

Entries are ``(path, label, type, description)``. Dict-valued payload keys
(values, changes, field_values, data, answers, …) can be drilled into —
``{{trigger.new_values.email}}`` resolves, because both resolvers walk nested
dicts.
"""

